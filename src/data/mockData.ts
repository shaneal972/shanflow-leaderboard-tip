export function getPublicLeaderboard(): LeaderboardApprenant[] {
  return MOCK_APPRENANTS
    .filter((a) => !a.is_admin)
    .map((a) => {
      const achievements = MOCK_ACHIEVEMENTS[a.id] || [];
      return {
        id: a.id,
        prenom: a.prenom,
        nom_initial: `${a.nom.charAt(0)}.`,
        avatar_url: a.avatar_url,
        points_total: a.points_total,
        palier_actuel: a.palier_actuel,
        equipe: a.equipe,
        badges_count: achievements.length,
      };
    })
    .sort((a, b) => b.points_total - a.points_total)
    .map((item, index) => ({
      ...item,
      rank: index + 1,
    }));
}
